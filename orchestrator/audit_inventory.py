HARDCODED_PATTERNS = [
    (r"/mnt/[a-zA-Z]", "WSL mount path (/mnt/*)"),
    (r"DRIVE_MASTER_DIR|DRIVE_HISTORICAL_DIR|DRIVE_F_DIR", "Workstation drive env vars"),
    (r"/tmp/scbv_reanalysis_scratch", "Hardcoded scratch path"),
    (r"FLeck_3R1|mosiac_1R|YLD_2R", "Hardcoded sample IDs"),
    (r"TGGTATCAGAGC", "Hardcoded Badnavirus tRNA-Met PBS motif"),
    (r"7000.*8500|6500.*8500", "Hardcoded SCBV 7-8kb length bounds"),
    (r"Sugarcane|Sugarbeet|RefBeet|SOH\.fa", "Hardcoded host reference names"),
]


def sha256_file(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def detect_language(path: pathlib.Path) -> str:
    ext = path.suffix.lower()
    return {
        ".py": "python",
        ".sh": "bash",
        ".r": "r",
        ".yml": "yaml",
        ".yaml": "yaml",
        ".md": "markdown",
    }.get(ext, "other")


def detect_tools_and_hardcoding(path: pathlib.Path) -> Tuple[str, str]:
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return ("none", "none")

    found_tools: List[str] = []
    lower_text = text.lower()
    for tool in EXTERNAL_TOOLS:
        if re.search(r"\b" + re.escape(tool.lower()) + r"\b", lower_text):
            found_tools.append(tool)

    found_hc: List[str] = []
    for pat, label in HARDCODED_PATTERNS:
        if re.search(pat, text):
            found_hc.append(label)

    return (
        ",".join(sorted(set(found_tools))) if found_tools else "none",
        "; ".join(found_hc) if found_hc else "none",
    )


