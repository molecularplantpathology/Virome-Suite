def main(root: pathlib.Path | None = None) -> None:
    if root is None:
        root = pathlib.Path(__file__).resolve().parent.parent
    scbv_dir = root / "r-pkg_tst" / "scripts" / "SCBV_all"
    virome_dir = root / "r-pkg_tst" / "scripts" / "VIROME_all"

    # Also index flattened/workflow copies to document exact hash matches
    other_dirs = [
        root / "r-pkg_tst" / "scripts",
        root / "r-pkg_tst" / "workflow",
    ]
    copy_hash_map: Dict[str, List[str]] = {}
    for odir in other_dirs:
        if not odir.exists():
            continue
        for f in odir.rglob("*"):
            if not f.is_file():
                continue
            rel_to_rpkg = str(f.relative_to(root / "r-pkg_tst")).replace("\\", "/")
            if rel_to_rpkg.startswith("scripts/SCBV_all/") or rel_to_rpkg.startswith("scripts/VIROME_all/"):
                continue
            h = sha256_file(f)
            copy_hash_map.setdefault(h, []).append(rel_to_rpkg)

    scbv_files = sorted([f for f in scbv_dir.rglob("*") if f.is_file()])
    virome_files = sorted([f for f in virome_dir.rglob("*") if f.is_file()])

    all_entries: List[Tuple[str, pathlib.Path, str]] = []
    for f in scbv_files:
        all_entries.append(("SCBV_all", f, str(f.relative_to(scbv_dir)).replace("\\", "/")))
    for f in virome_files:
        all_entries.append(("VIROME_all", f, str(f.relative_to(virome_dir)).replace("\\", "/")))

    manifest_path = root / "scripts_manifest.tsv"
    fieldnames = [
        "script_id",
        "source_collection",
        "relative_path",
        "sha256",
        "language",
        "size_bytes",
        "status",
        "license_provenance",
        "target_package",
        "external_tools",
        "hardcoded_assumptions",
        "duplicate_copies_in_repo",
        "generalization_action",
        "purpose",
    ]

    seen_hashes: Dict[str, str] = {}
    rows: List[Dict[str, str]] = []

    for idx, (group, fpath, rel_path) in enumerate(all_entries, start=1):
        sid = f"VS-{idx:03d}"
        h = sha256_file(fpath)
        lang = detect_language(fpath)
        size_b = fpath.stat().st_size
        status, lic, pkg, action, purpose = classify_script(group, rel_path)
        tools, hc = detect_tools_and_hardcoding(fpath)

        # Check if this file is an internal duplicate of an earlier file among the 263
        dup_list = list(copy_hash_map.get(h, []))
        if h in seen_hashes and status not in ("vendored", "spades_artifact"):
            status = f"duplicate_of_{seen_hashes[h]}"
        else:
            seen_hashes[h] = sid

        rows.append(
            {
                "script_id": sid,
                "source_collection": group,
                "relative_path": f"{group}/{rel_path}",
                "sha256": h[:16],
                "language": lang,
                "size_bytes": str(size_b),
                "status": status,
                "license_provenance": lic,
                "target_package": pkg,
                "external_tools": tools,
                "hardcoded_assumptions": hc,
                "duplicate_copies_in_repo": ",".join(dup_list) if dup_list else "none",
                "generalization_action": action,
                "purpose": purpose,
            }
        )

    with manifest_path.open("w", encoding="utf-8", newline="") as out_f:
        writer = csv.DictWriter(out_f, fieldnames=fieldnames, delimiter="\t")
        writer.writeheader()
        writer.writerows(rows)

    print(f"Generated {manifest_path} with {len(rows)} audited scripts.")


if __name__ == "__main__":
    main()
